"""日志层的两条**规则**（不是状态）：字符上限与截断。

**叶子模块**（一个包内 import 都没有），所以谁想按同一条规则截断都能来取。
⚠️ 但 `protocol.actions.describe` 那条边**仍然是注入而不是 import** ——
它的契约是"不认识日志"，见那边的说明。

**这里不放状态、不放 logger、不放格式化函数**，只放"上限"与"截断"这一件事。
"""

#: 日志里单个**输入字段**的**字符**上限，超了截断。**单位是字不是字节**
#: （中文 1 字 = 3 字节，按字节限同一个数字在中英文题目下差 3 倍）。
#: 第 26 步从 400 放宽到 **40000**（用户拍板"观察优先"：任务原文/回复/沙盒输出**基本不截**，
#: "日志长度不能是数据相关的量"那条旧原则就此让位）。代价 = 顶格字段一回合可写满
#: 64KB 管道（见 `CLAUDE.md` 硬约束 5）—— 已知并接受。
LOG_TEXT_MAX = 40000


def _clip(text: str, limit: int = LOG_TEXT_MAX) -> str:
    """超长文本截到 `limit` 字 —— **并且把截断这件事说出来**（`…（共 N 字）`）。

    **静默截断**是第 14 步被叫醒的那个坑：任务一长，日志里就是一段没头没尾的文字，
    看不出后面还有没有内容。被砍掉多少必须写在脸上。

    **`limit` 是个参数而不是两个函数**：截断规则（保头 + 留痕）只有这一份，唯一差别是上限
    （`prompt` 那一处用 `app.LOG_PROMPT_MAX`）。
    """
    if len(text) <= limit:
        return text
    return f"{text[:limit]}…（共 {len(text)} 字）"
