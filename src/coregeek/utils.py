"""日志层的两条**规则**（不是状态）：字符上限与截断。

**为什么要有这个文件。** `_clip` 原来住在 `app.py` 里 —— 而 `app` 是**组装根**，
在依赖图的最上面（`app → web / protocol / game`）。于是任何"想按同一条规则截断"的下游
都只能把它当**参数**递进去（`protocol.actions.describe` 正是这么做的，因为
`protocol` **不能** import `app`，那是反向依赖）。搬到这里（**叶子模块，一个包内
import 都没有**）之后，那条规则就只有一个位置，谁需要谁来取。

⚠️ 与 `agent` 那个叶子包的分工：那里是"跟 LLM 说什么"，这里是"日志打多少字"。
两者都是**与游戏无关**的机械规则，所以都不属于 `game`。

**这个文件里不放状态、不放 logger、不放格式化函数。** 只放"上限"与"截断"这一件事
—— 它是被 `app`、`protocol.actions`、以及将来任何日志消费者共用的那半条规则。
"""

#: 日志里单个**输入字段**的**字符**上限，超了截断。**单位是字不是字节**
#: （中文 1 字 = 3 字节，按字节数限制的话同一个数字在中英文题目下差 3 倍）。
#: 上限存在的理由与硬约束 5 同源：日志长度**不能是"数据相关的量"**，
#: 判题器给多长的任务原文不该决定我们写多少字节。
LOG_TEXT_MAX = 400


def _clip(text: str, limit: int = LOG_TEXT_MAX) -> str:
    """超长文本截到 `limit` 字（`LOG_TEXT_MAX`，只有 `prompt` 用 `LOG_PROMPT_MAX`）
    —— **并且把截断这件事说出来**。

    原来那版是 `text[:120]` 的**静默**截断：任务一长，日志里就是一段没头没尾的文字，
    看不出后面还有没有内容。第 14 步正是被这个坑叫醒的（"任务一直失败，
    把任务信息打印出来我看看"——打印了，但打印的是被砍过的）。被砍掉多少必须写在脸上。

    **`limit` 是个参数而不是两个函数**（第 20 步）：截断规则（保头 + 留痕）只有这一份，
    唯一的差别是上限 —— `prompt` 那一处用的是 `app.LOG_PROMPT_MAX`（1000，理由见那边）。
    `protocol.actions.describe` 也拿它当参数用（**注入而不是 import**：`describe` 的
    契约是"不认识日志"，把这个默认值塞进去就等于让 `protocol` 认识日志层了）。
    """
    if len(text) <= limit:
        return text
    return f"{text[:limit]}…（共 {len(text)} 字）"
